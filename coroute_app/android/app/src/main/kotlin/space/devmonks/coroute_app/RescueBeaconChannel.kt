/**
 * Round 10 rescue beacon (MethodChannel "coroute/rescue"; Dart: lib/data/services/rescue_native.dart).
 * Docs: docs/features_355/rescue_beacon.md, device checks: docs/quality/ROUND10_RESCUE_NOTES.md.
 *
 *  - playPcm / stopAudio / endSession: PCM16 mono from Dart (the siren + near-ultrasonic locator,
 *    generated by the same Dart code the lab tests) on an AudioTrack with USAGE_ALARM. The alarm
 *    stream is raised to max while the beacon runs and restored by endSession. With Do Not
 *    Disturb in "total silence" and CoRoute's Do Not Disturb access already granted, the filter is
 *    switched to "alarms only" for the beacon and restored after. No audio focus is requested
 *    (nothing can duck the siren).
 *  - vibrate: one waveform with alarm attributes.
 *  - strobe: the camera torch via CameraManager.setTorchMode (API 23+, needs NO camera permission;
 *    CAMERA stays removed from the manifest). The pattern from Dart is checked again here: any
 *    on + off cycle shorter than 334 ms is refused (never more than 3 flashes per second).
 *    Returns "torch", or "none" (no flash unit, camera busy): Dart then flashes the screen.
 *  - sensors: one short read of light, proximity and the accelerometer (face-down).
 *  - bleAdvertise: legacy advertising (all phones) plus, on Android 8+ with a chip that supports
 *    it, an extended advertising set on LE Coded PHY (long range) when supported. Service data
 *    under the rescue UUID, 5 bytes (lib/domain/rescue/rescue_ble.dart). No name, no position.
 *  - bleScan: scans for that service UUID only; results go to Dart as "onBleResult".
 *  - wakeLock: a partial wake lock with a timeout (re-taken by Dart while the beacon runs).
 * Every call answers on the main thread and never throws into Flutter.
 */
class RescueBeaconChannel(context: Context, private val channel: MethodChannel) : MethodChannel.MethodCallHandler {

    companion object {
        val SERVICE_UUID: UUID = UUID.fromString("6f1d0c2a-5b8e-4c37-9a41-2e7c5d0b9f13")
        private const val MIN_CYCLE_MS = 334
        private const val MAGIC = 0x52
        private const val VERSION = 1
    }

    private val app = context.applicationContext
    private val main = Handler(Looper.getMainLooper())
    private val audioLock = Any()

    // ---- audio
    @Volatile private var generation = 0
    private var track: AudioTrack? = null
    private var savedAlarmVolume = -1
    private var savedFilter = -1

    // ---- torch
    private var torchId: String? = null
    private var torchLit = false
    private var strobePattern: IntArray = IntArray(0)
    private var strobeIndex = 0
    private var strobing = false
    private val strobeStep = object : Runnable {
        override fun run() {
            if (!strobing || strobePattern.isEmpty()) return
            val on = strobeIndex % 2 == 0
            setTorch(on)
            val d = strobePattern[strobeIndex % strobePattern.size].toLong()
            strobeIndex = (strobeIndex + 1) % strobePattern.size
            main.postDelayed(this, d)
        }
    }

    // ---- BLE
    private var legacyCallback: AdvertiseCallback? = null
    private var setCallback: Any? = null // AdvertisingSetCallback on API 26+
    private var scanCallback: ScanCallback? = null

    // ---- wake lock
    private var wakeLock: PowerManager.WakeLock? = null

    override fun onMethodCall(call: MethodCall, result: MethodChannel.Result) {
        try {
            when (call.method) {
                "playPcm" -> result.success(playPcm(
                    call.argument<ByteArray>("pcm"),
                    call.argument<Int>("sampleRate") ?: 48000,
                    call.argument<Boolean>("alarm") != false,
                    call.argument<Boolean>("maxVolume") != false,
                ))
                "stopAudio" -> { stopAudio(); result.success(null) }
                "endSession" -> { endSession(); result.success(null) }
                "vibrate" -> { vibrate(call.argument<List<Int>>("pattern") ?: emptyList()); result.success(null) }
                "strobe" -> result.success(strobe(call.argument<Boolean>("on") == true, call.argument<List<Int>>("pattern") ?: emptyList()))
                "sensors" -> sensors(result)
                "bleAdvertise" -> result.success(bleAdvertise(
                    call.argument<Boolean>("on") == true,
                    call.argument<Int>("rescueId") ?: 0,
                    call.argument<Int>("flags") ?: 0,
                    call.argument<Boolean>("lowPower") == true,
                ))
                "bleScan" -> result.success(bleScan(call.argument<Boolean>("on") == true, call.argument<Boolean>("lowLatency") != false))
                "wakeLock" -> { wakeLock(call.argument<Boolean>("on") == true, (call.argument<Int>("timeoutMs") ?: 120000).toLong()); result.success(null) }
                "audioState" -> result.success(audioState())
                else -> result.notImplemented()
            }
        } catch (e: Exception) {
            result.error("RESCUE", e.message ?: e.javaClass.simpleName, null)
        }
    }

    // ================================================================== audio
    private fun audioManager(): AudioManager? = app.getSystemService(Context.AUDIO_SERVICE) as? AudioManager

    private fun playPcm(pcm: ByteArray?, sampleRate: Int, alarm: Boolean, maxVolume: Boolean): Boolean {
        if (pcm == null || pcm.size < 2) return false
        val rate = if (sampleRate in 8000..96000) sampleRate else 48000
        stopAudio()
        if (alarm && maxVolume) raiseAlarm()
        val myGen = synchronized(audioLock) { ++generation }
        val attrs = AudioAttributes.Builder()
            .setUsage(if (alarm) AudioAttributes.USAGE_ALARM else AudioAttributes.USAGE_MEDIA)
            .setContentType(AudioAttributes.CONTENT_TYPE_SONIFICATION)
            .build()
        val format = AudioFormat.Builder()
            .setSampleRate(rate)
            .setEncoding(AudioFormat.ENCODING_PCM_16BIT)
            .setChannelMask(AudioFormat.CHANNEL_OUT_MONO)
            .build()
        val minBuf = AudioTrack.getMinBufferSize(rate, AudioFormat.CHANNEL_OUT_MONO, AudioFormat.ENCODING_PCM_16BIT)
        val bufSize = if (minBuf > 0) maxOf(minBuf * 4, rate / 5 * 2) else rate / 5 * 2
        val t = try {
            AudioTrack.Builder()
                .setAudioAttributes(attrs)
                .setAudioFormat(format)
                .setBufferSizeInBytes(bufSize)
                .setTransferMode(AudioTrack.MODE_STREAM)
                .build()
        } catch (e: Exception) {
            return false
        }
        if (t.state != AudioTrack.STATE_INITIALIZED) {
            try { t.release() } catch (_: Exception) {}
            return false
        }
        synchronized(audioLock) { track = t }
        // Streaming writer: small chunks so a stop takes effect within ~100 ms.
        Thread({
            try {
                t.play()
                val chunk = (rate / 10) * 2 // 100 ms
                var off = 0
                while (off < pcm.size && generation == myGen) {
                    val n = minOf(chunk, pcm.size - off)
                    val w = t.write(pcm, off, n)
                    if (w <= 0) break
                    off += w
                }
                if (generation == myGen) {
                    // Let the buffered tail play out, then stop.
                    t.stop()
                    val tailMs = (bufSize / 2) * 1000L / rate + 50
                    Thread.sleep(tailMs)
                }
            } catch (_: Exception) {
            } finally {
                synchronized(audioLock) {
                    if (track === t) track = null
                }
                try { t.release() } catch (_: Exception) {}
            }
        }, "coroute-rescue-audio").start()
        return true
    }

    private fun stopAudio() {
        val t: AudioTrack?
        synchronized(audioLock) {
            generation++
            t = track
            track = null
        }
        if (t != null) {
            try { t.pause() } catch (_: Exception) {}
            try { t.flush() } catch (_: Exception) {}
            // The writer thread sees the new generation and releases the track.
        }
    }

    private fun raiseAlarm() {
        val am = audioManager() ?: return
        try {
            val max = am.getStreamMaxVolume(AudioManager.STREAM_ALARM)
            val cur = am.getStreamVolume(AudioManager.STREAM_ALARM)
            if (savedAlarmVolume < 0) savedAlarmVolume = cur
            if (cur < max) am.setStreamVolume(AudioManager.STREAM_ALARM, max, 0)
        } catch (_: Exception) {
            // Some phones refuse volume changes in Do Not Disturb: the siren still plays at the current level.
        }
        // Do Not Disturb "total silence" mutes alarms too. Only when the rider already gave CoRoute
        // Do Not Disturb access: switch to "alarms only" for the beacon (restored in endSession).
        try {
            val nm = app.getSystemService(Context.NOTIFICATION_SERVICE) as? NotificationManager
            if (nm != null && nm.isNotificationPolicyAccessGranted &&
                nm.currentInterruptionFilter == NotificationManager.INTERRUPTION_FILTER_NONE) {
                if (savedFilter < 0) savedFilter = nm.currentInterruptionFilter
                nm.setInterruptionFilter(NotificationManager.INTERRUPTION_FILTER_ALARMS)
            }
        } catch (_: Exception) {}
    }

    /** The beacon ended: silence, the rider's alarm volume and Do Not Disturb state back. */
    private fun endSession() {
        stopAudio()
        val am = audioManager()
        if (am != null && savedAlarmVolume >= 0) {
            try { am.setStreamVolume(AudioManager.STREAM_ALARM, savedAlarmVolume, 0) } catch (_: Exception) {}
        }
        savedAlarmVolume = -1
        if (savedFilter >= 0) {
            try {
                val nm = app.getSystemService(Context.NOTIFICATION_SERVICE) as? NotificationManager
                if (nm != null && nm.isNotificationPolicyAccessGranted) nm.setInterruptionFilter(savedFilter)
            } catch (_: Exception) {}
            savedFilter = -1
        }
        strobe(false, emptyList())
    }

    private fun audioState(): Map<String, Any?> {
        val am = audioManager()
        val nm = app.getSystemService(Context.NOTIFICATION_SERVICE) as? NotificationManager
        val adapter = bluetoothAdapter()
        val out = HashMap<String, Any?>()
        try {
            out["alarmVolume"] = am?.getStreamVolume(AudioManager.STREAM_ALARM)
            out["alarmMax"] = am?.getStreamMaxVolume(AudioManager.STREAM_ALARM)
            out["ringerMode"] = am?.ringerMode
            out["dndFilter"] = nm?.currentInterruptionFilter
            out["dndAccess"] = nm?.isNotificationPolicyAccessGranted
            out["torch"] = findTorch() != null
            out["bleOn"] = adapter?.isEnabled == true
            if (Build.VERSION.SDK_INT >= 26 && adapter != null) {
                out["bleExtended"] = adapter.isLeExtendedAdvertisingSupported
                out["bleCoded"] = adapter.isLeCodedPhySupported
            }
            out["bleMulti"] = adapter?.isMultipleAdvertisementSupported == true
        } catch (_: Exception) {}
        return out
    }

    // ================================================================== vibration
    private fun vibrate(pattern: List<Int>) {
        if (pattern.isEmpty()) return
        val timings = LongArray(pattern.size) { pattern[it].coerceIn(0, 5000).toLong() }
        @Suppress("DEPRECATION")
        val v = app.getSystemService(Context.VIBRATOR_SERVICE) as? Vibrator ?: return
        try {
            if (!v.hasVibrator()) return
            if (Build.VERSION.SDK_INT >= 33) {
                v.vibrate(
                    VibrationEffect.createWaveform(timings, -1),
                    VibrationAttributes.createForUsage(VibrationAttributes.USAGE_ALARM),
                )
            } else if (Build.VERSION.SDK_INT >= 26) {
                val attrs = AudioAttributes.Builder().setUsage(AudioAttributes.USAGE_ALARM).build()
                @Suppress("DEPRECATION")
                v.vibrate(VibrationEffect.createWaveform(timings, -1), attrs)
            } else {
                @Suppress("DEPRECATION")
                v.vibrate(timings, -1)
            }
        } catch (_: Exception) {}
    }

    // ================================================================== torch
    private fun cameraManager(): CameraManager? = app.getSystemService(Context.CAMERA_SERVICE) as? CameraManager

    private fun findTorch(): String? {
        torchId?.let { return it }
        val cm = cameraManager() ?: return null
        return try {
            var fallback: String? = null
            for (id in cm.cameraIdList) {
                val c = cm.getCameraCharacteristics(id)
                if (c.get(CameraCharacteristics.FLASH_INFO_AVAILABLE) != true) continue
                if (c.get(CameraCharacteristics.LENS_FACING) == CameraCharacteristics.LENS_FACING_BACK) {
                    torchId = id
                    return id
                }
                if (fallback == null) fallback = id
            }
            torchId = fallback
            fallback
        } catch (_: Exception) {
            null
        }
    }

    private fun setTorch(on: Boolean) {
        val id = torchId ?: return
        if (on == torchLit) return
        try {
            cameraManager()?.setTorchMode(id, on)
            torchLit = on
        } catch (_: Exception) {
            // Camera in use or the torch went away: stop strobing (Dart may flash the screen instead).
            strobing = false
            torchLit = false
        }
    }

    /** Starts / stops the torch pattern. Refuses any cycle faster than 3 per second. */
    private fun strobe(on: Boolean, pattern: List<Int>): String {
        main.removeCallbacks(strobeStep)
        if (!on) {
            strobing = false
            setTorch(false)
            return "off"
        }
        if (pattern.isEmpty() || pattern.size % 2 != 0) return "none"
        val p = IntArray(pattern.size) { pattern[it].coerceIn(1, 10000) }
        var i = 0
        while (i + 1 < p.size) {
            if (p[i] + p[i + 1] < MIN_CYCLE_MS) return "none" // photosensitivity guard
            i += 2
        }
        if (findTorch() == null) return "none"
        strobePattern = p
        strobeIndex = 0
        strobing = true
        // First flash now; a failure (camera busy) stops it and reports "none".
        setTorch(true)
        if (!strobing) return "none"
        setTorch(false)
        main.post(strobeStep)
        return "torch"
    }

    // ================================================================== sensors
    private fun sensors(result: MethodChannel.Result) {
        val sm = app.getSystemService(Context.SENSOR_SERVICE) as? SensorManager
        if (sm == null) {
            result.success(HashMap<String, Any?>())
            return
        }
        val prox = sm.getDefaultSensor(Sensor.TYPE_PROXIMITY)
        val light = sm.getDefaultSensor(Sensor.TYPE_LIGHT)
        val accel = sm.getDefaultSensor(Sensor.TYPE_ACCELEROMETER)
        val out = HashMap<String, Any?>()
        var answered = false
        lateinit var listener: SensorEventListener
        fun finish() {
            if (answered) return
            answered = true
            try { sm.unregisterListener(listener) } catch (_: Exception) {}
            result.success(out)
        }
        listener = object : SensorEventListener {
            override fun onSensorChanged(event: SensorEvent) {
                when (event.sensor.type) {
                    Sensor.TYPE_PROXIMITY -> if (!out.containsKey("proximityNear")) {
                        val range = event.sensor.maximumRange
                        out["proximityNear"] = event.values[0] < minOf(range, 5f)
                    }
                    Sensor.TYPE_LIGHT -> if (!out.containsKey("lux")) out["lux"] = event.values[0].toDouble()
                    Sensor.TYPE_ACCELEROMETER -> if (!out.containsKey("faceDown")) out["faceDown"] = event.values[2] < -7f
                }
                val want = (if (prox != null) 1 else 0) + (if (light != null) 1 else 0) + (if (accel != null) 1 else 0)
                if (out.size >= want) main.post { finish() }
            }

            override fun onAccuracyChanged(sensor: Sensor?, accuracy: Int) {}
        }
        try {
            if (prox != null) sm.registerListener(listener, prox, SensorManager.SENSOR_DELAY_NORMAL)
            if (light != null) sm.registerListener(listener, light, SensorManager.SENSOR_DELAY_NORMAL)
            if (accel != null) sm.registerListener(listener, accel, SensorManager.SENSOR_DELAY_NORMAL)
        } catch (_: Exception) {}
        if (prox == null && light == null && accel == null) {
            finish()
            return
        }
        main.postDelayed({ finish() }, 800)
    }

    // ================================================================== BLE
    private fun bluetoothAdapter(): BluetoothAdapter? =
        (app.getSystemService(Context.BLUETOOTH_SERVICE) as? BluetoothManager)?.adapter

    private fun granted(permission: String): Boolean =
        app.checkSelfPermission(permission) == PackageManager.PERMISSION_GRANTED

    private fun canAdvertise(): Boolean =
        if (Build.VERSION.SDK_INT >= 31) granted(Manifest.permission.BLUETOOTH_ADVERTISE) else true

    private fun canScan(): Boolean =
        if (Build.VERSION.SDK_INT >= 31) granted(Manifest.permission.BLUETOOTH_SCAN)
        else granted(Manifest.permission.ACCESS_FINE_LOCATION)

    @SuppressLint("MissingPermission") // checked in canAdvertise()
    private fun bleAdvertise(on: Boolean, rescueId: Int, flags: Int, lowPower: Boolean): Map<String, Any?> {
        val out = HashMap<String, Any?>()
        stopAdvertising()
        if (!on) return out
        if (rescueId <= 0 || rescueId > 0xFFFF) { out["error"] = "bad_id"; return out }
        val adapter = bluetoothAdapter()
        if (adapter == null) { out["error"] = "no_bluetooth"; return out }
        if (!canAdvertise()) { out["error"] = "no_permission"; return out }
        if (!adapter.isEnabled) { out["error"] = "bluetooth_off"; return out }
        val adv = adapter.bluetoothLeAdvertiser
        if (adv == null) { out["error"] = "no_advertiser"; return out }
        val payload = byteArrayOf(MAGIC.toByte(), VERSION.toByte(), ((rescueId shr 8) and 0xFF).toByte(), (rescueId and 0xFF).toByte(), (flags and 0xFF).toByte())
        val uuid = ParcelUuid(SERVICE_UUID)
        val data = AdvertiseData.Builder()
            .setIncludeDeviceName(false)
            .setIncludeTxPowerLevel(false)
            .addServiceData(uuid, payload)
            .build()
        // 1) Legacy advertising: every phone can scan it.
        try {
            val settings = AdvertiseSettings.Builder()
                .setAdvertiseMode(if (lowPower) AdvertiseSettings.ADVERTISE_MODE_LOW_POWER else AdvertiseSettings.ADVERTISE_MODE_BALANCED)
                .setTxPowerLevel(AdvertiseSettings.ADVERTISE_TX_POWER_HIGH)
                .setConnectable(false)
                .setTimeout(0)
                .build()
            val cb = object : AdvertiseCallback() {
                override fun onStartFailure(errorCode: Int) {
                    main.post { if (legacyCallback === this) legacyCallback = null }
                }
            }
            adv.startAdvertising(settings, data, cb)
            legacyCallback = cb
            out["legacy"] = true
        } catch (e: Exception) {
            out["error"] = "legacy_" + e.javaClass.simpleName
        }
        // 2) Extended advertising on LE Coded PHY (Android 8+, chip support, room for a second set).
        if (Build.VERSION.SDK_INT >= 26 && adapter.isLeExtendedAdvertisingSupported &&
            (legacyCallback == null || adapter.isMultipleAdvertisementSupported)) {
            try {
                val coded = adapter.isLeCodedPhySupported
                val phy = if (coded) BluetoothDevice.PHY_LE_CODED else BluetoothDevice.PHY_LE_1M
                val params = AdvertisingSetParameters.Builder()
                    .setLegacyMode(false)
                    .setConnectable(false)
                    .setScannable(false)
                    .setInterval(if (lowPower) AdvertisingSetParameters.INTERVAL_HIGH else AdvertisingSetParameters.INTERVAL_MEDIUM)
                    .setTxPowerLevel(AdvertisingSetParameters.TX_POWER_HIGH)
                    .setPrimaryPhy(phy)
                    .setSecondaryPhy(phy)
                    .build()
                val cb = object : AdvertisingSetCallback() {
                    override fun onAdvertisingSetStarted(advertisingSet: AdvertisingSet?, txPower: Int, status: Int) {
                        if (status != AdvertisingSetCallback.ADVERTISE_SUCCESS) main.post { if (setCallback === this) setCallback = null }
                    }
                }
                adv.startAdvertisingSet(params, data, null, null, null, cb)
                setCallback = cb
                out["extended"] = true
                out["coded"] = coded
            } catch (e: Exception) {
                if (out["error"] == null) out["error"] = "extended_" + e.javaClass.simpleName
            }
        }
        return out
    }

    @SuppressLint("MissingPermission") // a stop without the permission throws SecurityException, caught
    private fun stopAdvertising() {
        val adv = try { bluetoothAdapter()?.bluetoothLeAdvertiser } catch (_: Exception) { null }
        legacyCallback?.let { cb -> try { adv?.stopAdvertising(cb) } catch (_: Exception) {} }
        legacyCallback = null
        if (Build.VERSION.SDK_INT >= 26) {
            val cb = setCallback
            if (cb is AdvertisingSetCallback) {
                try { adv?.stopAdvertisingSet(cb) } catch (_: Exception) {}
            }
        }
        setCallback = null
    }

    @SuppressLint("MissingPermission") // checked in canScan()
    private fun bleScan(on: Boolean, lowLatency: Boolean): Boolean {
        val adapter = bluetoothAdapter()
        val scanner = try { adapter?.bluetoothLeScanner } catch (_: Exception) { null }
        scanCallback?.let { cb -> try { scanner?.stopScan(cb) } catch (_: Exception) {} }
        scanCallback = null
        if (!on) return true
        if (adapter == null || scanner == null || !adapter.isEnabled || !canScan()) return false
        val filter = ScanFilter.Builder().setServiceData(ParcelUuid(SERVICE_UUID), byteArrayOf(MAGIC.toByte()), byteArrayOf(0xFF.toByte())).build()
        val sb = ScanSettings.Builder()
            .setScanMode(if (lowLatency) ScanSettings.SCAN_MODE_LOW_LATENCY else ScanSettings.SCAN_MODE_BALANCED)
            .setReportDelay(0)
        if (Build.VERSION.SDK_INT >= 26 && adapter.isLeExtendedAdvertisingSupported) {
            // Also hear the extended (LE Coded) set.
            sb.setLegacy(false)
            sb.setPhy(ScanSettings.PHY_LE_ALL_SUPPORTED)
        }
        val cb = object : ScanCallback() {
            override fun onScanResult(callbackType: Int, result: ScanResult) {
                deliver(result)
            }

            override fun onBatchScanResults(results: MutableList<ScanResult>) {
                for (r in results) deliver(r)
            }
        }
        return try {
            scanner.startScan(listOf(filter), sb.build(), cb)
            scanCallback = cb
            true
        } catch (_: Exception) {
            false
        }
    }

    private fun deliver(r: ScanResult) {
        val data = r.scanRecord?.getServiceData(ParcelUuid(SERVICE_UUID)) ?: return
        if (data.size < 4 || (data[0].toInt() and 0xFF) != MAGIC || (data[1].toInt() and 0xFF) != VERSION) return
        val id = ((data[2].toInt() and 0xFF) shl 8) or (data[3].toInt() and 0xFF)
        if (id == 0) return
        val m = HashMap<String, Any?>()
        m["rescueId"] = id
        m["rssi"] = r.rssi
        if (Build.VERSION.SDK_INT >= 26) {
            m["phy"] = when (r.primaryPhy) {
                BluetoothDevice.PHY_LE_CODED -> "coded"
                BluetoothDevice.PHY_LE_2M -> "2m"
                else -> "1m"
            }
        }
        main.post {
            try { channel.invokeMethod("onBleResult", m) } catch (_: Exception) {}
        }
    }

    // ================================================================== wake lock
    private fun wakeLock(on: Boolean, timeoutMs: Long) {
        if (on) {
            val pm = app.getSystemService(Context.POWER_SERVICE) as? PowerManager ?: return
            val wl = wakeLock ?: pm.newWakeLock(PowerManager.PARTIAL_WAKE_LOCK, "coroute:rescue").also {
                it.setReferenceCounted(false)
                wakeLock = it
            }
            try { wl.acquire(timeoutMs.coerceIn(10_000L, 600_000L)) } catch (_: Exception) {}
        } else {
            try { if (wakeLock?.isHeld == true) wakeLock?.release() } catch (_: Exception) {}
        }
    }

    /** The Flutter engine goes away: nothing may keep sounding, flashing or advertising. */
    fun dispose() {
        endSession()
        stopAdvertising()
        bleScan(false, false)
        wakeLock(false, 0)
        main.removeCallbacksAndMessages(null)
    }
}
